const STAGE_DUTY: Record<CreationStage, string> = {
  outline:
    '你负责整个故事的结构：主线走向、分卷与分卷的因果、冲突的升级曲线、伏笔的埋与收。' +
    '这一层也管**分卷**——把全书切成若干卷，以及把一卷切成一个个剧情段。\n' +
    '你不写具体场景，也不写正文——那是后面几层的事。',
  // 这一层是整套设计最容易被写歪的地方，所以把「不做什么」写得比「做什么」更细。
  // 从前它要求给出这一章的开头与结尾画面——那既抢了场景层的活，又逼着每一章
  // 强行自成起讫，而长篇小说的剧情本来就是连续的。
  plot:
    '你负责把故事往前推：这一章发生什么、事件之间的因果、冲突在哪一步翻转、' +
    '谁付出什么代价、最后收在什么局面上。\n' +
    '**你交出的是剧情脉络，不是场景。** 不要写具体的画面、天气、动作细节或台词——' +
    '那是下一层的事；也不要规定这一章从哪句话开头、到哪句话结尾，那是写正文时才定的东西。\n' +
    '你也不必让这一章自成起讫：它是一条连续剧情里的一截，前面接着上一章的局面，' +
    '后面留给下一章。写多长由剧情本身决定——正文出来后作者会自己决定在哪里断章，' +
    '所以不必为了凑够一章而注水，也不必为了收在一章之内而强行收束。',
  scene:
    '你负责把这一幕**想具体**：站在什么地方、什么天气什么光线、人物做了哪些动作、' +
    '说了哪些话、哪些细节值得写进去。你产出的是写正文时能直接取用的素材，' +
    '不是对正文的规定——你不写正文，也不给写正文的人立规矩。',
  manuscript:
    '你负责把已经定好的剧情写成文学文本。剧情走向不由你决定——那在本章剧情里已经定了。' +
    '上面给出的场景素材（环境、动作、对话、细节）是**供你取用的材料**，不是必须逐条落实的清单：' +
    '该用的用，该舍的舍，也可以自己补更好的写法。你要交出的是读起来像小说的文字。',
};

/** 每种能力要模型做什么。与阶段无关的那一半。 */
const CAPABILITY_TASK: Record<Capability, string> = {
  discuss: '作者要和你讨论。他问什么你答什么：要建议给建议，要分析给分析，要判断给判断。',
  expand:
    '作者要你在现有产物上补充内容。只补该补的地方，明确说出你加了什么、加在哪一节，' +
    '不要把已经写好的部分重述一遍。',
  critique:
    '作者要你挑刺。找逻辑漏洞、动机不足、冲突太弱、节奏平、巧合过多、人物做了不像他会做的事。' +
    '**只说问题和改法，不要顺手替他改写。** 挑不出真问题就直说没有，不要为了凑数编。',
  check:
    '作者要你对账：把当前内容与已给出的设定、角色、伏笔、时间线逐条比对，找出**冲突**。' +
    '每条都要指出与什么冲突、依据是上面哪一段。没有冲突就明确说没有。',
  split:
    '作者要你把当前这一层拆成下一层。拆出来的每一项都要能独立成立，不要留「后面再说」的空档。' +
    '**要拆成几项由下面的输出契约说**——它说只给一项时就只给一项。',
  generate:
    '作者已经描述了他想要的走向（见下面「我的要求」）。**按他说的产出**，不要另起炉灶改走向；' +
    '他没说到的地方，顺着已有设定与前后文补上，别停在半截。',
  // 这一条与 generate 的差别就是这次改动要的两条路：一条从作者的描述出发，
  // 一条从刚发生过的讨论出发。说不清「以哪边为准」，模型会把两者混着编。
  settle:
    '你和作者刚讨论完这一章（完整对话就在上面）。把讨论中**已经达成的结论**整理成产物。\n' +
    '以讨论里定下的为准：**不要塞进讨论中被否掉的方案**，也不要临时发明谁都没提过的新走向。\n' +
    '讨论中悬而未决的地方，按最接近的结论写或留空，并在产物之外用一两句话说明哪几处还没定——' +
    '那正是作者接下来要接着聊的东西。',
  rewrite: '作者要你拿着他的修改意见重做一版。采纳他的意见，同时保留上一版里写得好的部分。',
};

/**
 * 系统提示词。
 *
 * 正文阶段的六条硬性要求逐字保留——它们是这个项目跑了很久、调出来的东西
 * （不复述前情、不写章节标题、不强行收束…），换个说法就等于重新试错一遍。
 */
export function buildSystemPrompt(action: CreationAction, config: NovelConfig, targetWords?: number): string {
  const { stage, capability } = action;

  // 正文 + 出稿：沿用原有的写作提示词，一字不改。
  if (stage === 'manuscript' && (capability === 'generate' || capability === 'rewrite')) {
    const lines = [
      '你是一位资深中文长篇小说作者，正在为一部已连载的作品续写新的章节。',
      '',
      '硬性要求：',
      '1. 严格贴合已给出的文风指南与上文语气，读者应当感觉不到换人执笔。',
      '2. 人物的性格、称谓、说话习惯必须与角色设定一致，不得凭空改变人物关系或已确立的设定。',
      '3. 完整覆盖本章剧情纲要中的每一个要点，按纲要顺序推进，并把它扩写成有场景、有对白、有细节的成稿。',
      '4. 不要复述前情，不要写「上回说到」，直接从上一章结尾的情境自然接续。',
      '5. 只输出正文。不要输出章节标题、小标题、分隔线、创作说明、字数统计或任何元信息。',
      '6. 不要在结尾强行收束或做总结陈词，留出继续往下写的余地。',
    ];
    if (targetWords) {
      lines.push(`7. 篇幅控制在约 ${targetWords} 字。`);
    }
    lines.push('', `叙事语言：简体中文。温度设定 ${config.temperature}，请在保持稳定的前提下让文字有生气。`);
    return lines.join('\n');
  }

  const lines = [
    `你是一位${STAGE_ROLE[stage]}，正在协助作者推进一部长篇中文小说。`,
    '',
    STAGE_DUTY[stage],
    '',
    CAPABILITY_TASK[capability],
    '',
    '通用要求：',
    '1. 一切判断建立在已给出的文风指南、设定、角色卡与前文之上，不要凭空发明设定。',
    '2. 发现作者的想法与既有设定冲突（人物性格、已收伏笔、时间线）时必须直说，并给出可行的调整方案。',
    '3. 具体，不要泛泛而谈。能引用上面给出的原文就引用。',
  ];

  if (outputKindOf(action) === 'text') {
    // 这一条是「讨论型能力」的边界。少了它，模型会一边回答一边把整份产物
    // 重写一遍，而界面上那一版是不能采纳的，用户只会困惑。
    lines.push('4. **只回答，不要输出改写后的完整产物。** 需要落到文件上的改动由作者另行发起。');
  }

  lines.push('', '语言：简体中文。');
  return lines.join('\n');
}

/**
 * 大纲 → 分卷清单。
 *
 * 从前这一步直接拆成「一章一章的剧情」。跨度太大：全书大纲那一两千字里没有
 * 足够的信息去决定第 7 章该发生什么，模型只能一次吐五章骨架，而那五章彼此的
 * 因果薄得像一份目录。中间插一层卷，每一卷是一条完整的中等弧线。
 */
const SPLIT_OUTLINE_INTO_VOLUMES = [
  '请把上面的大纲拆成若干卷，只输出 JSON，不要有任何其它文字：',
  '',
  '```json',
  '{"volumes":[{"no":1,"title":"觉醒之日","goal":"林昭活着走出青云镇，并知道自己身上那道印记是什么",' +
    '"arc":"从她在客栈发烧醒来开始……最后收在她决定往北走。"}]}',
  '```',
  '',
  '一卷是一条完整的中等弧线：有自己的开局、升级与收束，通常十几到几十万字。',
  'goal 必须是一个能判断「达成没达成」的具体结果，不要写「继续推进剧情」这种。',
  'arc 写这一卷的剧情走向：从什么局面开始、经过哪些事、收在什么局面上，几句话即可，' +
    '细的走向留给「写这一卷的卷纲」那一步。',
  '**不要在这里切剧情段**——那是下一步的事，而且一次只切一段。',
].join('\n');

/**
 * 卷纲 → **一个**剧情段。
 *
 * 一次一段是刻意的。一次吐五段只会得到一串彼此没有因果的骨架（那正是「大纲直接
 * 拆章」的老毛病）；一次一段时，模型手上有卷纲、也有这一卷已经排到哪了，
 * 「接下来该发生什么」才答得准。上下文里那两层（`volumeSelf` / `volumeSegments`）
 * 就是为这一步铺的。
 */
const SPLIT_VOLUME_INTO_SEGMENT = [
  '请从这一卷里拆出**下一个**剧情段，只输出 JSON，不要有任何其它文字：',
  '',
  '```json',
  '{"plots":[{"title":"楼道","goal":"林昭拿到三楼那把钥匙，同时被邻居认出来",' +
    '"arc":"第一幕 · 入局"}]}',
  '```',
  '',
  '**只给一段。** 上面已经列出这一卷排到哪了（若还没有，这就是第一段）——' +
  '你要给的是紧接着它往下的那一段，不是重复已有的，也不是跳到后面去的。',
  '一段是一段按剧情自然长度展开的内容：它不必正好凑成一章，写出来之后由作者' +
  '决定在哪里断章。所以不要为了凑一章而注水，也不要为了收在一章之内而强行收束。',
  'goal 必须是一个能判断「达成没达成」的具体结果，不要写「继续推进剧情」这种。',
  'arc 可选，写它属于这一卷的哪一幕；说不清就留空字符串。',
].join('\n');

/**
 * 输出契约：附在 user 消息末尾的那段「现在请你产出什么」。
 *
 * 结构化产物一律要求 JSON。解析侧必须三层降级（JSON → Markdown 小节 → 全文），
 * 与单章摘要同一套——模型不听话是常态，而解析失败等于这一次生成白花钱。
 */
export function buildOutputContract(
  action: CreationAction,
  targetWords?: number,
  targetKind?: CreationTarget['kind']
): string {
  const { stage, capability } = action;

  if (outputKindOf(action) === 'text') {
    return capability === 'critique'
      ? '请直接给出你发现的问题，每条说明「问题是什么 / 为什么是问题 / 可以怎么改」。不要输出改写后的完整产物。'
      : capability === 'check'
        ? '请逐条列出你发现的冲突，每条注明与上面哪一段设定/前文冲突。没有冲突就明确说明没有。'
        : '请直接回答上面的问题。若我要的是建议或分析，就给建议或分析，不必写成小说正文。';
  }

  switch (stage) {
    case 'outline':
      // 大纲这一层有两种 target，`split` 在两者上要的东西完全不同：全书大纲拆出
      // 分卷清单，一卷拆出**一个**剧情段。判据与 `parseArtifact` 同源。
      if (capability === 'split') {
        return targetKind === 'volume' ? SPLIT_VOLUME_INTO_SEGMENT : SPLIT_OUTLINE_INTO_VOLUMES;
      }
      return targetKind === 'volume'
        ? [
            '请输出这一卷完整的卷纲，用 Markdown 小节书写，小节名就用下面这四个：',
            '',
            ...VOLUME_SECTION_KEYS.map((k) => `## ${k}`),
            '',
            '「目标」一句话说清这一卷要达成什么，必须是能判断「达成没达成」的具体结果。',
            '「剧情走向」是主体：这一卷从什么局面开始、经过哪些事、收在什么局面上，' +
              '按因果顺序写。它是拆剧情段的依据，写到「能据此判断下一段该发生什么」为止。',
            '「关键转折」说清这一卷的主冲突是什么、在哪一步翻转、谁付出什么代价。',
            '「伏笔与回收」分别写清这一卷埋下什么、兑现了前面哪一处。',
            '**不要写具体画面、天气、动作细节或台词**，也不要把这一卷预先切成段——' +
              '切段是下一步的事，一次一段地做。',
            '只输出卷纲本身，不要解释你改了什么。',
          ].join('\n')
        : [
            '请输出修订后的完整大纲，用 Markdown 分卷书写（`## 第一卷 · 觉醒之日`）。',
            '每一卷下列出若干剧情节点，每个节点一行，说清「谁做了什么、导致什么」。',
            '只输出大纲本身，不要解释你改了什么。',
          ].join('\n');

    case 'plot':
      if (capability === 'split') {
        return [
          '请把这一章的剧情拆成若干场景，只输出 JSON，不要有任何其它文字：',
          '',
          '```json',
          '{"scenes":[{"title":"翻越侧峰","place":"青云宗侧峰","time":"子时，暴雨",' +
            '"characters":["林昭"],"goal":"进入青云宗","targetWords":1000}]}',
          '```',
          '',
          '一章通常 3~6 场。每一场都要有自己的目的与一个可以失败的点；',
          '把「路上无事发生」这类没有戏剧动作的段落合并掉，不要单独成场。',
        ].join('\n');
      }
      return [
        '请输出这一章的剧情细纲，只输出 JSON，不要有任何其它文字：',
        '',
        '```json',
        '{' + PLOT_SECTION_KEYS.map((k) => `"${k}":"…"`).join(',') + '}',
        '```',
        '',
        '「剧情脉络」是主体：把事件按因果顺序列出来——谁做了什么、导致什么、于是谁不得不做什么。',
        '最后一环写清这一章收在什么局面上（谁在哪、关系变成什么样、谁知道了什么），下一章从那里接。',
        '**不要写具体画面、天气、动作细节或台词**，那些在场景层。也不要规定这一章的开头与结尾。',
        '「冲突与转折」说清主冲突是什么、在哪一步翻转、谁付出什么代价。',
        '「伏笔与回收」分别写清这一章埋下什么、兑现了前面哪一处。',
        '想不清楚的小节留空字符串，不要为了填满而编。' +
          (targetWords ? `\n这一章目标篇幅约 ${targetWords} 字，据此把握事件密度。` : ''),
      ].join('\n');

    case 'scene':
      return [
        '请为这一幕准备素材，只输出 JSON，不要有任何其它文字：',
        '',
        '```json',
        '{"place":"…","time":"…","characters":["…"],"targetWords":1000,' +
          SCENE_SECTION_KEYS.map((k) => `"${k}":"…"`).join(',') +
          '}',
        '```',
        '',
        '各节写什么：',
        '- 「目的」一句话说清这一幕在本章里担什么用，供写正文的人定位，不必展开。',
        '- 「环境」写此刻的天气、光线、声音、气味、地方的样子，具体到能看见。',
        '- 「人物状态」写各人此刻的身体状态与心里在意的事，以及他知道什么、还不知道什么。',
        '- 「动作」写他们具体做了什么，一步一步的实际动作，不是「他很紧张」这种概括。',
        '- 「对话」写几句真正说出口的话，标明谁说的。宁可少而准，不要写成台词大纲。',
        '- 「细节与意象」挑几个值得落笔的物件、身体感觉或反复出现的意象。',
        '',
        '要求：',
        '1. **写具体的东西，不写抽象的要求。**「雨里的灯只剩一团黄」是素材，' +
          '「要营造压抑氛围」不是——后者写正文的人用不上。',
        '2. **不要给正文立规矩。** 不要写这一幕应该达到什么效果、必须包含哪些要点、' +
          '哪些内容不许出现。剧情走向在上一层已经定了，你的活是把它想成画面。',
        '3. 你给的素材允许被取舍。多给一点可用的东西，让写的人挑，不要写成一份必须逐条落实的清单。',
        '4. 用不上的小节留空字符串，不要为了填满而编。',
      ].join('\n');

    case 'manuscript':
      return `现在开始写作。只输出小说正文，不要输出任何标题、序号、解释、总结或「以下是」之类的话。`;
  }
}

/**
 * 用户输入那一段的小标题。
 *
 * 「本章剧情纲要（必须完整覆盖）」这种说法只在正文阶段成立——在剧情阶段
 * 用户输入的是要求而不是纲要，照搬会让模型以为要把那句话扩写成正文。
 */
export function askHeading(action: CreationAction): string {
  if (action.stage === 'manuscript' && (action.capability === 'generate' || action.capability === 'rewrite')) {
    return '# 本章剧情纲要（必须完整覆盖，按顺序推进）';
  }
  return '# 我的要求';
}
