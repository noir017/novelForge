/**
 * 建条目与整合转写那一步的 JSON 合同（2026-10-25 起改成转写）：把按 {@link LORE_ENTRY_SYSTEM} 写的条目搬成
 * features/lore.ts 的 `parseEntryDraft` 认的 `{brief, keywords, body}`，`body` 是从「## 概要」起的整段 Markdown。
 */
export function loreEntryJsonContract(): string {
  return [
    '【设定条目 JSON 合同】',
    '只输出 {"brief":"…","keywords":["…"],"body":"…"}：',
    '- brief：「一句话：」那一行冒号后面的话；keywords：「关键词：」那一行里的叫法，一个一项。',
    '- body：从「## 概要」起到原文末尾的全部内容，连「## 」小标题与换行一起照抄成一段 Markdown（JSON 里换行写成 \\n）；不含「一句话」「关键词」那两行。',
    '- 写「无」或没有的：文字给 ""，列表给 []。',
    '- 文字一律从原文照抄：不改写、不总结、不润色，不补原文没有的，也不删原文写了的。',
    '只输出一个可由 JSON.parse 读取的 JSON 对象，不要解释、Markdown 或代码围栏。',
    '【JSON 形状】{"brief":"…","keywords":["…"],"body":"## 概要\\n…\\n\\n## 规则与边界\\n…\\n\\n## 现状\\n…"}',
  ].join('\n');
}

