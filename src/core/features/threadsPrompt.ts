/** 排线。`totalChapters` 不知道时不写章号上限；`mainExists` 时叫它别再排主线。 */
export function threadPlanSystem(totalChapters?: number, mainExists = false): string {
  const range = totalChapters ? `1..${totalChapters} 范围内的整数` : '正整数';
  return `你是长篇小说的结构编辑。只从作者给的小说配置、故事前提、角色图谱与情节大纲里排出这本书的叙事线（剧情线），以及挂在每条线下面的伏笔。只写计划，不得声称正文事件已经发生。

请只输出一个 JSON 对象，除 JSON 外不要输出任何文字、解释或前后缀：

{
  "threads": [
    {
      "title": "线的名字，12 字以内，例如「林昭与沈青」「沈家旧案」",
      "kind": "主线 / 支线 / 感情线 / 人物线 之一",
      "from": 3,
      "to": 40,
      "intent": "这条线从哪里走到哪里、在哪里收住，100 字以内",
      "foreshadowing": [
        { "title": "伏笔的名字，12 字以内，例如「玉佩的来历」", "what": "这条伏笔是什么、真相是什么，60 字以内", "plant": 3, "resolve": 18 }
      ]
    }
  ]
}

要求：
- 叙事线只收剧情线，种类必须是主线、支线、感情线、人物线之一：主线是全书的主干，全书只有一条${mainExists ? '（已经有了，这一次不要再排主线）' : ''}；支线是主线之外自成首尾的事件线；感情线是两个人之间关系的走向；人物线是一个人的成长或变化。不分子线。
- 「玉佩的来历」「师父的身份」这种要先埋下、日后揭开的东西是伏笔，不是线：写进它所属那条线的 foreshadowing 里。每条线最多 5 条伏笔，没有就给空数组。
- from 是计划在第几章开始，to 是计划在第几章收住；plant 是计划在第几章埋下，resolve 是计划在第几章之前收回。都必须是 ${range}，from ≤ to，plant ≤ resolve；说不准的可以不写。
- 每一条线、每一条伏笔都要在情节大纲、故事前提或角色图谱里说得出依据。角色图谱里写着的「暗设」是读者还不知道的真相，适合排成伏笔（伏笔管什么时候、怎么揭开，真相照暗设写）。
- 优先排 3–8 条真正撑得起几十章的线；不足 3 条时不要凑数。最多 8 条。
- 已有的线与伏笔不要再提，也不要换个名字再提一遍；「未归属的伏笔」不能用作线名。
- 所有内容用简体中文。`;
}

/** 定稿第三步 a：认事件。替换七期的 THREAD_EVENT_SYSTEM。 */
export const THREAD_FIND_SYSTEM = `你是小说定稿事实审查员。只根据这一章已定稿的正文，认出它在叙事线上发生了什么：给出的线推进了哪几条、伏笔埋了或收了哪几条、人物关系有没有变；正文里第一次出现、却还没有记下的剧情线与伏笔也认出来。不推测正文没写的事。

请只输出一个 JSON 对象，除 JSON 外不要输出任何文字、解释或前后缀：

{
  "events": [
    { "line": "线的名字，与给出的完全一致", "type": "推进 / 关系 / 收束 / 放弃 / 埋 / 收 / 弃 之一", "foreshadowing": "伏笔的名字（埋、收、弃才写）", "what": "一句话说发生了什么，40 字以内", "evidence": "正文里逐字出现的一句短摘录，80 字以内" }
  ],
  "newThreads": [
    { "title": "新线的名字，12 字以内", "kind": "主线 / 支线 / 感情线 / 人物线 之一", "intent": "这条线是什么、大概会往哪走，60 字以内", "evidence": "正文里逐字出现的一句短摘录" }
  ],
  "newForeshadowing": [
    { "title": "新伏笔的名字，12 字以内", "what": "埋下的是什么，40 字以内", "line": "挂在哪条线上（给出的线或新线的名字；挂不上就不写）", "evidence": "正文里逐字出现的一句短摘录" }
  ]
}

七种类型：
- 推进：这条线有了新的进展，但还没走完；
- 关系：两个人之间的关系变了（what 写「甲—乙，原来 → 现在」），挂在相关的那条线上（感情线、人物线最常见）；
- 收束：这条线走完了；
- 放弃：正文明确让这条线作废（极少用）；
- 埋：一条伏笔在正文里第一次露出来；
- 收：一条伏笔揭开了、兑现了；
- 弃：正文明确让一条伏笔作废（极少用）。

要求：
- 证据必须从正文里逐字复制，不改一个字、不把两处拼在一起；找不到原句的不要列。
- 线的事件（推进、关系、收束、放弃）的 line 只能是给出的线，或这一次 newThreads 里的线；伏笔的事件（埋、收、弃）必须写 foreshadowing，给出的伏笔照抄名字。
- 「本章计划」里写的是这一章本来要干什么，只用来帮你认；正文里没写到的不要列。
- 新线只收剧情线（种类四选一），主线全书只有一条；「玉佩的来历」这种要日后揭开的东西是伏笔，不是线。已经给出的线与伏笔不要当新的再报。
- 一条线在本章没有动静就不要列；什么都没有就返回 {"events": [], "newThreads": [], "newForeshadowing": []}。
- 事件最多 8 条，新线最多 2 条，新伏笔最多 5 条。所有内容用简体中文。`;

